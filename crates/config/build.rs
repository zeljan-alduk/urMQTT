//! The only build-time switch left (ADR-216): is this a development
//! kernel (`URMQTT_ENV=dev`, the default) or the release kernel (any other
//! value; every such build is the same kernel)? A dev kernel also carries
//! one device certificate for in-kernel self-tests that need a TLS client
//! (`test=dp-bench`); the release kernel carries none. Everything else is
//! data the bootloader hands the kernel at boot (the `urmqtt-cfg` blob).

use std::path::PathBuf;
use std::{env, fs, process};

fn fail(msg: &str) -> ! {
    eprintln!("error: {msg}");
    process::exit(1);
}

fn main() {
    println!("cargo::rerun-if-env-changed=URMQTT_ENV");
    let dev = env::var("URMQTT_ENV").map_or(true, |v| v == "dev");

    let manifest = PathBuf::from(
        env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|_| fail("CARGO_MANIFEST_DIR not set")),
    );
    let root = manifest
        .ancestors()
        .nth(2)
        .unwrap_or_else(|| fail("cannot locate workspace root"));
    let dir = root.join("deploy").join("dev");

    let (cert, key) = if dev {
        let embed = |name: &str| -> String {
            let path = dir.join(name);
            println!("cargo::rerun-if-changed={}", path.display());
            if !path.exists() {
                fail(&format!(
                    "cannot read {}\n  hint: run `make certs` to generate development certificates",
                    path.display()
                ));
            }
            format!(
                "include_bytes!({:?})",
                path.to_str()
                    .unwrap_or_else(|| fail(&format!("{} is not valid UTF-8", path.display())))
            )
        };
        (
            embed("devices/device-001.pem"),
            embed("devices/device-001.key"),
        )
    } else {
        ("&[]".to_owned(), "&[]".to_owned())
    };

    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap_or_else(|_| fail("OUT_DIR not set")));
    let generated = format!(
        "// @generated by crates/config/build.rs. Do not edit.\n\n\
         /// A development kernel: accepts `env = \"dev\"` configurations (plaintext port,\n\
         /// durability shortcuts) and carries the self-test client. The release kernel\n\
         /// refuses such a configuration.\n\
         pub const DEV_KERNEL: bool = {dev};\n\
         /// Dev kernels: device-001's certificate for self-tests (empty otherwise).\n\
         pub static SELFTEST_CLIENT_CERT_PEM: &[u8] = {cert};\n\
         /// Dev kernels: device-001's key for self-tests (empty otherwise).\n\
         pub static SELFTEST_CLIENT_KEY_PEM: &[u8] = {key};\n"
    );
    fs::write(out_dir.join("generated.rs"), generated)
        .unwrap_or_else(|e| fail(&format!("cannot write generated.rs: {e}")));
}
