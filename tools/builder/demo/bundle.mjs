// Assembles the "Try urMQTT live" page into a directory (default build/demo): app.js from the modules in src/ (the same
// no-bundler concatenation as tools/builder/web/bundle.mjs: import and export keywords removed, one function scope,
// so every top-level name of src/ must be unique), app.css, index.html (standalone), the texts and a manifest with
// content hashes. If scripts/demo-certs.sh has made deploy/demo/pki/download, it is copied to certs/ (the page links
// certs/demo-certs.zip).
//
//   node tools/builder/demo/bundle.mjs [OUT_DIR]
import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '../../..');
const OUT = resolve(process.argv[2] || join(ROOT, 'build/demo'));
const SRC = join(HERE, 'src');
const ORDER = ['mqtt.js', 'demo.js'];

function strip(name, text) {
  let out = text;
  out = out.replace(/^import\s[^;]*?from\s*['"][^'"]+['"];?[ \t]*\n/gm, '');
  out = out.replace(/^export\s+(default\s+)?(async\s+function|function\*?|const|let|class)\b/gm, '$2');
  out = out.replace(/^export\s*\{[^}]*\};?[ \t]*\n/gm, '');
  const left = out.match(/^\s*(import|export)\b/m);
  if (left) throw new Error(`${name}: an import/export form the bundler does not handle: ${left[0].trim()}`);
  return `// ---- ${name} ----\n${out}`;
}

mkdirSync(OUT, { recursive: true });
const unknown = readdirSync(SRC).filter(n => n.endsWith('.js') && !ORDER.includes(n));
if (unknown.length) throw new Error(`src/ has modules that are not in the bundle order: ${unknown.join(', ')}`);
const js = `// urMQTT live demo page (generated by tools/builder/demo/bundle.mjs; do not edit)\n(() => {\n'use strict';\n${ORDER.map(n => strip(n, readFileSync(join(SRC, n), 'utf8'))).join('\n')}\n})();\n`;
writeFileSync(join(OUT, 'app.js'), js);
cpSync(join(HERE, 'app.css'), join(OUT, 'app.css'));
rmSync(join(OUT, 'i18n'), { recursive: true, force: true });
cpSync(join(HERE, 'i18n'), join(OUT, 'i18n'), { recursive: true });

rmSync(join(OUT, 'certs'), { recursive: true, force: true });
const pki = join(ROOT, 'deploy/demo/pki/download');
let certs = false;
if (existsSync(join(pki, 'demo-certs.zip'))) {
  mkdirSync(join(OUT, 'certs'), { recursive: true });
  cpSync(join(pki, 'demo-certs.zip'), join(OUT, 'certs/demo-certs.zip'));
  cpSync(join(pki, 'README.txt'), join(OUT, 'certs/README.txt'));
  certs = true;
}

const hashes = {};
const walk = (dir, rel = '') => {
  for (const e of readdirSync(join(dir, rel), { withFileTypes: true })) {
    const r = rel ? `${rel}/${e.name}` : e.name;
    if (e.isDirectory()) walk(dir, r);
    else if (e.name !== 'manifest.json' && e.name !== 'index.html' && !r.startsWith('certs/')) hashes[r] = createHash('sha256').update(readFileSync(join(dir, r))).digest('hex').slice(0, 10);
  }
};
walk(OUT);
let html = readFileSync(join(HERE, 'index.html'), 'utf8');
html = html.replace(/__V:([A-Za-z0-9_./-]+)__/g, (m, f) => {
  if (!hashes[f]) throw new Error(`index.html names ${f}, which is not built`);
  return hashes[f];
});
writeFileSync(join(OUT, 'index.html'), html);
writeFileSync(join(OUT, 'manifest.json'), JSON.stringify({ files: hashes, certs }, null, 2) + '\n');
console.log(`demo page: ${Object.keys(hashes).length} files in ${OUT}${certs ? ', with the certificate download' : ', WITHOUT the certificate download (run scripts/demo-certs.sh first)'}`);
