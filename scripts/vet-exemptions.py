#!/usr/bin/env python3
"""Lists the cargo-vet exemptions by role, for docs/audit/vet-exemptions.md (H9, ADR-191).

    scripts/vet-exemptions.py           write docs/audit/vet-exemptions.md
    scripts/vet-exemptions.py --check   fail if it is out of date

An exemption is a crate version that is neither audited by this project nor
covered by an imported audit (supply-chain/config.toml `[imports.*]`): it is
trusted on reputation, the lockfile pin and cargo-deny only. The roles come
from scripts/sbom.py (kernel = linked into an image; build-time = proc-macro
or build script of a kernel; host-tool = tests, tools and the host build).
Deterministic: no dates.
"""

import importlib.util
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "audit" / "vet-exemptions.md"


def load_sbom():
    spec = importlib.util.spec_from_file_location("sbom", ROOT / "scripts" / "sbom.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def render():
    cfg = tomllib.loads((ROOT / "supply-chain" / "config.toml").read_text())
    ex = {}
    for name, items in cfg.get("exemptions", {}).items():
        for it in items:
            ex[(name, it["version"])] = it["criteria"]
    sbom = load_sbom()
    warnings = []
    role = sbom.roles(warnings)
    if warnings:
        raise SystemExit("; ".join(warnings))
    rows = {"kernel": [], "build-time": [], "host-tool": []}
    for (n, v), crit in sorted(ex.items()):
        rows[role.get((n, v), "host-tool")].append((n, v, crit))
    kernel_all = sorted(k for k, r in role.items() if r == "kernel")
    covered = [k for k in kernel_all if k not in ex]
    out = [
        "<!-- Generated by scripts/vet-exemptions.py; do not edit. -->",
        "",
        "# cargo-vet exemptions",
        "",
        f"{len(ex)} exemptions in `supply-chain/config.toml`. An exemption is a crate version that is neither "
        "audited by this project nor covered by an imported audit: it is trusted on the registry's reputation, "
        "the lockfile pin and `cargo deny` only. See docs/SUPPLY-CHAIN.md for what that means and the plan to "
        "reduce them.",
        "",
        "| Role | Crate versions linked | Exempt | Covered by imported audits |",
        "|---|---:|---:|---:|",
        f"| linked into a kernel (TCB) | {len(kernel_all)} | {len(rows['kernel'])} | {len(covered)} |",
        f"| build time (proc-macro, build script) | - | {len(rows['build-time'])} | - |",
        f"| host only (tools, tests, build host) | - | {len(rows['host-tool'])} | - |",
        "",
        "The vendored, patched crates (`cpufeatures` 0.2.17 and 0.3.1, `primeorder` 0.14.0) are first-party for "
        "cargo-vet (`audit-as-crates-io = false`): they are not the crates.io bytes. They are reviewed as a diff "
        "against the pinned upstream (vendor/README.md).",
        "",
    ]
    titles = {
        "kernel": "Linked into a kernel: exempt (the TCB gap)",
        "build-time": "Build time only: exempt",
        "host-tool": "Host only: exempt",
    }
    for k in ("kernel", "build-time", "host-tool"):
        out += [f"## {titles[k]}", "", "| Crate | Version | Criteria |", "|---|---|---|"]
        out += [f"| `{n}` | {v} | {c} |" for n, v, c in rows[k]]
        out.append("")
    out += ["## Linked into a kernel and covered by an imported audit", "", "| Crate | Version |", "|---|---|"]
    out += [f"| `{n}` | {v} |" for n, v in covered]
    out.append("")
    return "\n".join(out)


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("out of date: docs/audit/vet-exemptions.md (run scripts/vet-exemptions.py)")
            sys.exit(1)
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
