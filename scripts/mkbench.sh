#!/usr/bin/env bash
# Builds the BENCHMARK universal ISO (PERF, ADR-082): the production
# configuration with the handshake limits relaxed, so that one source address
# (a load generator on a laptop) can load the server. NEVER for serving
# devices.
#
#   scripts/mkbench.sh [--certs DIR] [--static ADDR/LEN GATEWAY] [--serve-dispatcher]
#                      [--env NAME] [--no-build]
#
#   --certs DIR           where ca.pem, ca.key, server.pem, server.key and
#                         control.pub (and devices/, services/) come from
#                         (default deploy/prod). They are copied, never moved.
#   --static ADDR/LEN GW  a fixed address instead of DHCP, e.g. a VPS:
#                         --static 169.58.184.193/17 169.58.128.1
#   --serve-dispatcher    cpu.dispatcher_serves = true (ADR-081)
#   --env NAME            the build environment and its deploy/NAME directory
#                         (default bench-local; git ignores it, so the copied
#                         keys and the address never reach a commit)
#   --no-build            only prepare deploy/NAME
#
# The template is deploy/bench/config.toml; everything else in it is the
# production configuration. Then:
#
#   target/release/urmqtt-loadgen handshake --host VPS --port 8883 \
#       --certs deploy/bench-local --threads 256 --duration 30
#
# loadgen takes its client certificates from the CA in --certs, so the
# directory must hold ca.key too (it is copied from --certs).
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
CERTS="$ROOT/deploy/prod" ENVNAME=bench-local STATIC="" GW="" SERVE=0 BUILD=1
while [[ $# -gt 0 ]]; do
    case $1 in
        --certs) CERTS=$2; shift 2 ;;
        --static) STATIC=$2 GW=$3; shift 3 ;;
        --serve-dispatcher) SERVE=1; shift ;;
        --env) ENVNAME=$2; shift 2 ;;
        --no-build) BUILD=0; shift ;;
        *) echo "unknown argument: $1" >&2; exit 2 ;;
    esac
done
case $ENVNAME in
    dev|prod|bench) echo "refusing to overwrite deploy/$ENVNAME: pick another --env" >&2; exit 2 ;;
esac
DEST="$ROOT/deploy/$ENVNAME"
mkdir -p "$DEST"
for f in ca.pem ca.key server.pem server.key control.pub; do
    [[ -f "$CERTS/$f" ]] || { echo "missing $CERTS/$f" >&2; exit 1; }
    cp "$CERTS/$f" "$DEST/$f"
done
for d in devices services; do
    [[ -d "$CERTS/$d" ]] && { rm -rf "${DEST:?}/$d"; cp -R "$CERTS/$d" "$DEST/$d"; }
done
python3 -I - "$ROOT/deploy/bench/config.toml" "$DEST/config.toml" "$STATIC" "$GW" "$SERVE" <<'EOF'
import sys
src, dst, static, gw, serve = sys.argv[1:6]
s = open(src).read()
if static:
    old = 'mode = "dhcp"'
    assert old in s, "the template has no dhcp network mode"
    s = s.replace(
        s[s.index(old):s.index("\n", s.index(old))],
        f'mode = "static"\naddress = "{static}"\ngateway = "{gw}"',
        1,
    )
if serve == "1":
    assert "dispatcher_serves = false" in s
    s = s.replace("dispatcher_serves = false", "dispatcher_serves = true", 1)
header = "# GENERATED by scripts/mkbench.sh from deploy/bench/config.toml. BENCHMARK ONLY.\n"
open(dst, "w").write(header + s)
EOF
echo "mkbench: deploy/$ENVNAME ready ($([[ -n $STATIC ]] && echo "static $STATIC via $GW" || echo dhcp)$([[ $SERVE == 1 ]] && echo ", dispatcher serves"))"
if [[ $BUILD == 1 ]]; then
    cd "$ROOT"
    make universal ENV="$ENVNAME"
fi
